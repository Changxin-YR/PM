"""Render physical foreign keys from a migrated PostgreSQL schema without reading business rows."""
import argparse
from pathlib import Path

import sqlalchemy as sa
from sqlalchemy.engine import Connection

from pmo.db import engine


def render(conn: Connection) -> str:
    schema = conn.scalar(sa.text('SELECT current_schema()'))
    version_table = sa.table('alembic_version', sa.column('version_num'), schema=schema)
    version = conn.execute(sa.select(version_table.c.version_num)).scalar_one()
    inspector = sa.inspect(conn)
    columns = inspector.get_multi_columns(schema=schema)
    primary = inspector.get_multi_pk_constraint(schema=schema)
    unique = inspector.get_multi_unique_constraints(schema=schema)
    foreign = inspector.get_multi_foreign_keys(schema=schema)
    edges, linked = [], set()
    for key, constraints in foreign.items():
        _, child = key
        keys = [primary[key]['constrained_columns'], *(item['column_names'] for item in unique[key])]
        nullable = {col['name'] for col in columns[key] if col['nullable']}
        for fk in constraints:
            if fk['referred_schema'] not in (None, schema):
                raise ValueError(f"Foreign key crosses PMO schema: {child}.{fk['name']}")
            parent = fk['referred_table']
            source, target = fk['constrained_columns'], fk['referred_columns']
            parent_end = 'o|' if nullable.intersection(source) else '||'
            child_end = 'o|' if any(cols and set(cols).issubset(source) for cols in keys) else 'o{'
            label = '+'.join(source)
            if target != ['id'] or len(source) > 1:
                label += ' to ' + '+'.join(target)
            edges.append((child, label, f'    {parent} {parent_end}..{child_end} {child} : "{label}"'))
            linked.update((parent, child))
    others = sorted(name for _, name in columns if name not in linked and name != 'alembic_version')
    lines = [
        f'# PostgreSQL relationships (revision {version})', '',
        'Generated by `python -m scripts.schema_erd` from a fully migrated PostgreSQL schema;',
        'checked against a fresh migration in `tests/test_runtime.py`. No business records are read.', '',
        f'{len(columns) - 1} application tables and {len(edges)} physical foreign keys (excluding `alembic_version`).',
        'Composite columns are joined with `+`. Cardinalities use nullability and unconditional PK/UNIQUE',
        'constraints only. The diagram does not assert application authorization, partial uniqueness,',
        'polymorphic references, immutable-history triggers, or every field in the frozen data dictionary.', '',
        '```mermaid', 'erDiagram', *(line for _, _, line in sorted(edges)), '```', '',
        'Tables without a physical foreign-key edge:', '',
        *(f'- `{name}`' for name in others), '',
    ]
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', type=Path, help='compare with a tracked ERD instead of printing')
    args = parser.parse_args()
    with engine().connect() as conn:
        conn.exec_driver_sql('SET TRANSACTION READ ONLY')
        current = render(conn)
    if args.check is None:
        print(current, end='')
    elif current != args.check.read_text(encoding='utf-8'):
        raise SystemExit('ERD differs from the connected PostgreSQL schema; check the Alembic head and regenerate it')
    else:
        print(f'PASS: {args.check} matches actual PostgreSQL foreign keys')


if __name__ == '__main__':
    main()
