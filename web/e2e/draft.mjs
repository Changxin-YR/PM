import {chromium,expect} from '@playwright/test'
import {mkdir} from 'node:fs/promises'

const browser=await chromium.launch({channel:process.env.PMO_BROWSER_CHANNEL || (process.platform==='win32'?'msedge':'chromium')})
try {
  const page=await browser.newPage({viewport:{width:1280,height:768}})
  await page.goto(process.env.PMO_BROWSER_URL)
  await page.getByLabel('账号',{exact:true}).fill(process.env.PMO_TEST_USER)
  await page.getByLabel('密码',{exact:true}).fill(process.env.PMO_TEST_PASSWORD)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('button',{name:'新建项目'}).click()
  await page.getByLabel('项目编号').fill('E2E-001')
  await page.getByLabel('项目名称',{exact:true}).fill('交付演练')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.getByRole('button',{name:'查看 交付演练 的项目资料'})).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'修改草稿名称'}).click()
  await page.getByLabel('项目名称',{exact:true}).fill('试点范围复核')
  await page.getByRole('button',{name:'保存',exact:true}).click()
  await expect(page.getByRole('button',{name:'查看 试点范围复核 的项目资料'})).toBeVisible()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.getByRole('button',{name:'查看 试点范围复核 的项目资料'}).click()
  const drawer=page.getByRole('dialog')
  await drawer.getByRole('button',{name:'新增里程碑'}).click()
  await drawer.getByLabel('里程碑名称').fill('交付节点')
  await drawer.getByLabel('计划日期').fill('2027-01-20')
  await drawer.getByLabel('关键里程碑').check()
  await drawer.getByRole('button',{name:'保存里程碑'}).click()
  await drawer.getByRole('button',{name:'编辑里程碑'}).click()
  await drawer.getByLabel('预测日期').fill('2027-01-19')
  await drawer.getByRole('button',{name:'保存里程碑'}).click()
  await drawer.getByRole('button',{name:'刷新里程碑'}).click()
  await expect(drawer.getByRole('cell',{name:'2027-01-19'})).toBeVisible()
  await drawer.getByRole('tab',{name:'需求',exact:true}).click()
  await drawer.getByRole('button',{name:'新增需求'}).click()
  await drawer.getByLabel('需求描述').fill('导出交付验证记录')
  await drawer.getByLabel('验收标准').fill('导出文件与原始记录逐行相同')
  await drawer.getByLabel('计划确认日期').fill('2027-01-25')
  await drawer.getByRole('button',{name:'保存需求'}).click()
  await drawer.getByRole('button',{name:'编辑需求'}).click()
  await expect(drawer.getByLabel('验收标准')).toHaveValue('导出文件与原始记录逐行相同')
  await drawer.getByLabel('优先级',{exact:true}).selectOption('P0')
  await drawer.getByRole('button',{name:'保存需求'}).click()
  await expect(drawer.getByRole('cell',{name:'P0',exact:true})).toBeVisible()
  await drawer.getByRole('tab',{name:'立项卡',exact:true}).click()
  await drawer.getByLabel('价值主张').fill('减少项目重复填报')
  await drawer.getByLabel('粗估金额（元）').fill('109.70')
  await drawer.getByLabel('粗估人天').fill('2.25')
  await drawer.getByRole('button',{name:'添加风险'}).click()
  await drawer.getByLabel('风险描述',{exact:true}).fill('评审材料缺失')
  await drawer.getByLabel('应对措施',{exact:true}).fill('提交前核对清单')
  await drawer.getByRole('button',{name:'保存立项卡'}).click()
  await expect(drawer.getByRole('status')).toHaveText('已保存')
  await drawer.getByRole('button',{name:'重新读取立项卡'}).click()
  await expect(drawer.getByLabel('风险描述',{exact:true})).toHaveValue('评审材料缺失')
  await expect(drawer.getByLabel('粗估金额（元）')).toHaveValue('109.70')
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await mkdir('test-results',{recursive:true})
  await page.screenshot({path:'test-results/ledger-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'test-results/ledger-mobile.png'})
  await expect(page.getByRole('button',{name:'新建项目'})).toBeInViewport()
  await page.getByRole('button',{name:'退出登录'}).click()
  await expect(page.getByRole('heading',{name:'登录工作台'})).toBeVisible()
} finally {await browser.close()}
